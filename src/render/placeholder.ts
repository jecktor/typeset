let cached: Uint8Array | null = null;

/** PNG bytes of the built-in placeholder. Decoded once per process. */
export function placeholderImageBytes(): Uint8Array {
  if (cached) return cached;
  cached = decodeBase64(PLACEHOLDER_PNG_BASE64);
  return cached;
}

/** atob in browsers and modern Node; Buffer only as a legacy-runtime fallback. */
function decodeBase64(base64: string): Uint8Array {
  const g = globalThis as unknown as {
    atob?: (data: string) => string;
    Buffer?: { from(data: string, encoding: string): Uint8Array };
  };
  if (typeof g.atob === 'function') {
    const binary = g.atob(base64);
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
    return bytes;
  }
  if (g.Buffer) return new Uint8Array(g.Buffer.from(base64, 'base64'));
  throw new Error('No base64 decoder available in this runtime');
}
